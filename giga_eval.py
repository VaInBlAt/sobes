def evaluate_task3(student_answer: str, questions: str, description: str) -> dict:
    """Полная проверка монолога: основы, фактическая точность, логика.

    Args:
        student_answer: Распознанный ответ ученика (монолог).
        questions: Вопросы-опоры, склеенные через перевод строки.
        description: Заранее подготовленное подробное описание фотографии.

    Returns:
        Словарь ``{"stems": int, "facts_ok": bool, "logic_ok": bool, "note": str}``.
    """
    client = _get_client()

    user_prompt = (
        f"Эталонное описание фотографии:\n{description}\n\n"
        f"Вопросы-опоры:\n{questions}\n\n"
        f"Ответ ученика:\n{student_answer}\n\n"
        "Верни строго JSON по инструкции."
    )
    payload = Chat(
        messages=[
            Messages(role=MessagesRole.SYSTEM, content=TASK3_FACTS_PROMPT),
            Messages(role=MessagesRole.USER, content=user_prompt),
        ],
        temperature=0.0,
        max_tokens=300,
    )
    response = client.chat(payload)
    raw = (response.choices[0].message.content or "").strip()
    data = _parse_json(raw)

    # stems может прийти строкой — приводим аккуратно.
    stems_raw = data.get("stems", 0)
    try:
        stems = int(stems_raw)
    except (TypeError, ValueError):
        stems = 0

    return {
        "stems": stems,
        "facts_ok": bool(data.get("facts_ok", False)),
        "logic_ok": bool(data.get("logic_ok", False)),
        "note": str(data.get("note", "") or ""),
    }