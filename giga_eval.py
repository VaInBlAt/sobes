_client = None


def _get_client() -> GigaChat:
    """Создаёт (один раз) и возвращает клиент GigaChat."""
    global _client
    if _client is None:
        _client = GigaChat(
            base_url=GIGACHAT_BASE_URL,
            credentials=GIGACHAT_CREDENTIALS,
            ca_bundle_file=GIGACHAT_CA_BUNDLE,
            model=GIGACHAT_MODEL,
        )
    return _client


def _extract_digit(raw: str) -> int:
    for ch in (raw or ""):
        if ch in ("0", "1"):
            return int(ch)
    return 0


def _parse_json(raw: str) -> dict:
    """Достаёт JSON из ответа модели. Терпит ```json ...``` и мусор вокруг."""
    raw = (raw or "").strip()
    if raw.startswith("```"):
        raw = raw.strip("`").strip()
        if raw.lower().startswith("json"):
            raw = raw[4:].strip()
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        lo, hi = raw.find("{"), raw.rfind("}")
        if lo != -1 and hi > lo:
            try:
                return json.loads(raw[lo:hi + 1])
            except json.JSONDecodeError:
                pass
    return {}


def evaluate_student_answer(student_answer: str, question: str, text: str) -> int:
    """Оценивает ответ ученика на вопрос по исходному тексту через GigaChat.

    Модель получает вопрос, ответ ученика и исходный текст задания 1,
    а также строгий системный промпт с правилами ФИПИ (см. ``SYSTEM_PROMPT``)
    и должна вернуть ровно один символ — ``1`` или ``0``.

    Args:
        student_answer: Распознанный ответ ученика.
        question: Вопрос, на который отвечал ученик.
        text: Исходный текст задания 1.

    Returns:
        Целое число: ``1`` — ответ зачтён, ``0`` — не зачтён.

    Raises:
        gigachat.exceptions.GigaChatException: Если запрос к API не удался.
    """
    client = _get_client()

    user_prompt = (
        f"Вопрос: {question}\n\n"
        f"Текст:\n{text}\n\n"
        f"Ответ ученика: {student_answer}\n\n"
        "Проверь по правилам и выведи строго один символ: 1 или 0."
    )

    payload = Chat(
        messages=[
            Messages(role=MessagesRole.SYSTEM, content=SYSTEM_PROMPT),
            Messages(role=MessagesRole.USER, content=user_prompt),
        ],
        temperature=0.0,
        max_tokens=8,
    )

    response = client.chat(payload)
    raw = (response.choices[0].message.content or "").strip()
    return _extract_digit(raw)


